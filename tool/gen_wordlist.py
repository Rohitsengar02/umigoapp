#!/usr/bin/env python3
"""Copies server/moderator/wordlist.json into lib/moderation/wordlist.dart so app + Umi Guard share one list."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((root / 'server/moderator/wordlist.json').read_text(encoding='utf-8'))
out = ['// GENERATED by tool/gen_wordlist.py from server/moderator/wordlist.json. Do not edit by hand.', '']
out.append('const modLists = <String, List<String>>{')
for k, v in d.items():
    if k.startswith('_'):
        continue
    out.append(f"  '{k}': [")
    for w in v:
        out.append('    ' + json.dumps(w, ensure_ascii=False).replace('$', '\\$') + ',')
    out.append('  ],')
out.append('};')
(root / 'lib/moderation/wordlist.dart').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('wrote lib/moderation/wordlist.dart')
